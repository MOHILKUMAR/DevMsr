/**
 * Generates supabase/seed.sql from the typed seed files in src/data.
 *
 *   npm run seed:generate
 *
 * The same files power the bundled fallback catalogue, so the database seed
 * and the fallback can never drift apart. The generated SQL is idempotent:
 * re-running it does not duplicate rows or overwrite edits made in the admin.
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { INDUSTRY_CONTENT } from '../src/data/industries.ts';
import { SERVICE_SEED } from '../src/data/seed/services.ts';
import { PRICING_SEED } from '../src/data/seed/pricing.ts';
import { BLOG_SEED, FAQ_SEED, PORTFOLIO_SEED, PRODUCT_SEED, SITE_SETTINGS_SEED } from '../src/data/seed/content.ts';

const q = (value: string | null | undefined): string => (value === null || value === undefined ? 'null' : `'${value.replace(/'/g, "''")}'`);
const arr = (items: readonly string[] | undefined): string => (!items || items.length === 0 ? `'{}'::text[]` : `array[${items.map(q).join(', ')}]::text[]`);
const bool = (value: boolean): string => (value ? 'true' : 'false');

const lines: string[] = [];
const out = (line = '') => lines.push(line);

out('-- =====================================================================');
out('-- DevMsr.in seed data — GENERATED by scripts/generate-seed.ts.');
out('-- Do not edit by hand; edit src/data/** and run `npm run seed:generate`.');
out('-- Idempotent: safe to run more than once; never overwrites admin edits.');
out('-- =====================================================================');
out();
out('begin;');
out();

out('-- Industries');
for (const industry of INDUSTRY_CONTENT) {
  out(
    `insert into public.industries (slug, name, description, icon, sort_order) values (${q(industry.slug)}, ${q(industry.name)}, ${q(industry.description)}, ${q(industry.icon)}, ${industry.sortOrder}) on conflict (slug) do nothing;`,
  );
}
out();

out('-- Services');
SERVICE_SEED.forEach((service, index) => {
  out(
    `insert into public.services (slug, name, short_description, category, features, status, sort_order) values (${q(service.slug)}, ${q(service.name)}, ${q(service.shortDescription)}, ${q(service.category)}, ${arr(service.features)}, ${q(service.status ?? 'offered')}, ${(index + 1) * 10}) on conflict (slug) do nothing;`,
  );
});
out();

out('-- Service ↔ industry links');
for (const service of SERVICE_SEED) {
  for (const industry of service.industries) {
    out(
      `insert into public.service_industries (service_id, industry_id) select s.id, i.id from public.services s, public.industries i where s.slug = ${q(service.slug)} and i.slug = ${q(industry)} on conflict do nothing;`,
    );
  }
}
out();

out('-- Indicative pricing (amounts are exact numerics)');
PRICING_SEED.forEach((row, index) => {
  out(
    `insert into public.service_pricing (service_id, label, display_group, pricing_model, minimum_amount, maximum_amount, max_open_ended, billing_interval, price_note, included_features, excluded_features, sort_order)
select s.id, ${q(row.label)}, ${q(row.group)}, ${q(row.model ?? 'range')}, ${row.min === null ? 'null' : `${row.min}::numeric`}, ${row.max === null ? 'null' : `${row.max}::numeric`}, ${bool(row.maxOpenEnded ?? false)}, ${q(row.interval ?? 'one_time')}, ${q(row.note)}, ${arr(row.included)}, ${arr(row.excluded)}, ${(index + 1) * 10}
from public.services s
where s.slug = ${q(row.serviceSlug)}
  and not exists (select 1 from public.service_pricing p where p.service_id = s.id and p.label = ${q(row.label)});`,
  );
});
out();

out('-- Products (statuses are deliberately conservative; see src/data/seed/content.ts)');
PRODUCT_SEED.forEach((product, index) => {
  out(
    `insert into public.products (slug, name, summary, description, status, industry_id, service_category, features, technology_stack, sort_order, is_published)
values (${q(product.slug)}, ${q(product.name)}, ${q(product.summary)}, ${q(product.description)}, ${q(product.status)}, ${product.industrySlug ? `(select id from public.industries where slug = ${q(product.industrySlug)})` : 'null'}, ${q(product.serviceCategory)}, ${arr(product.features)}, ${arr(product.technologyStack)}, ${(index + 1) * 10}, true)
on conflict (slug) do nothing;`,
  );
});
out();

out('-- Portfolio');
for (const project of PORTFOLIO_SEED) {
  out(
    `insert into public.portfolio_projects (slug, title, summary, description, project_type, technology_stack, demo_url, is_published)
values (${q(project.slug)}, ${q(project.title)}, ${q(project.summary)}, ${q(project.description)}, ${q(project.projectType)}, ${arr(project.technologyStack)}, ${q(project.demoUrl)}, true)
on conflict (slug) do nothing;`,
  );
}
out();

out('-- Blog');
for (const post of BLOG_SEED) {
  out(
    `insert into public.blog_posts (slug, title, excerpt, content, status, published_at)
values (${q(post.slug)}, ${q(post.title)}, ${q(post.excerpt)}, ${q(post.content)}, ${q(post.status)}, ${post.publishedAt ? `${q(post.publishedAt)}::timestamptz` : 'null'})
on conflict (slug) do nothing;`,
  );
}
out();

out('-- FAQs');
FAQ_SEED.forEach((faq, index) => {
  const industry = faq.scope === 'industry' ? `(select id from public.industries where slug = ${q(faq.scopeKey)})` : 'null';
  const category = faq.scope === 'service_category' ? q(faq.scopeKey) : 'null';
  out(
    `insert into public.faqs (scope, industry_id, service_category, question, answer, sort_order)
select ${q(faq.scope)}, ${industry}, ${category}, ${q(faq.question)}, ${q(faq.answer)}, ${(index + 1) * 10}
where not exists (select 1 from public.faqs f where f.question = ${q(faq.question)});`,
  );
});
out();

out('-- Site settings (null values are shown only after you set them in /admin/settings)');
for (const [key, value] of Object.entries(SITE_SETTINGS_SEED)) {
  out(`insert into public.site_settings (key, value) values (${q(key)}, ${q(JSON.stringify(value))}::jsonb) on conflict (key) do nothing;`);
}
out();
out('commit;');

const target = fileURLToPath(new URL('../supabase/seed.sql', import.meta.url));
writeFileSync(target, `${lines.join('\n')}\n`, 'utf8');
console.log(`Wrote ${target}`);
console.log(
  `  ${INDUSTRY_CONTENT.length} industries, ${SERVICE_SEED.length} services, ${PRICING_SEED.length} prices, ${PRODUCT_SEED.length} products, ${PORTFOLIO_SEED.length} portfolio, ${BLOG_SEED.length} posts, ${FAQ_SEED.length} FAQs`,
);
